#!/usr/bin/env bash
set -euo pipefail
: "${1:?window}"
case "$1" in
  Y2016) START=04/01/2016; EVAL=2016-01-11T00:00:00Z; END=30/12/2016; YEARS=1.0;;
  Y2017) START=03/01/2017; EVAL=2017-01-10T00:00:00Z; END=29/12/2017; YEARS=1.0;;
  Y2018) START=02/01/2018; EVAL=2018-01-09T00:00:00Z; END=31/12/2018; YEARS=1.0;;
  Y2019) START=02/01/2019; EVAL=2019-01-09T00:00:00Z; END=31/12/2019; YEARS=1.0;;
  Y2020) START=02/01/2020; EVAL=2020-01-09T00:00:00Z; END=31/12/2020; YEARS=1.0;;
  Y2021) START=04/01/2021; EVAL=2021-01-11T00:00:00Z; END=31/12/2021; YEARS=1.0;;
  Y2022) START=03/01/2022; EVAL=2022-01-10T00:00:00Z; END=30/12/2022; YEARS=1.0;;
  Y2023) START=02/01/2023; EVAL=2023-01-09T00:00:00Z; END=29/12/2023; YEARS=1.0;;
  H2024H2) START=01/07/2024; EVAL=2024-07-08T00:00:00Z; END=31/12/2024; YEARS=.5;;
  H2025H1) START=02/01/2025; EVAL=2025-01-09T00:00:00Z; END=30/06/2025; YEARS=.5;;
  H2025H2) START=01/07/2025; EVAL=2025-07-08T00:00:00Z; END=31/12/2025; YEARS=.5;;
  Q12026) START=02/01/2026; EVAL=2026-01-09T00:00:00Z; END=31/03/2026; YEARS=.25;;
  Q22026) START=01/04/2026; EVAL=2026-04-08T00:00:00Z; END=30/06/2026; YEARS=.25;;
  Q32026) START=01/07/2026; EVAL=2026-07-08T00:00:00Z; END=30/09/2026; YEARS=.25;;
  *) echo "unknown window $1" >&2; exit 64;;
esac
printf 'START=%q\nEVAL=%q\nEND=%q\nYEARS=%q\n' "$START" "$EVAL" "$END" "$YEARS"
